void fill_out_whole_screen(void) {
	SSD1306_SendData(screen_data, SCREEN_DATA_SIZE);
	return;
}

void fill_out_screen_data_with_zeroes (void) {
	for (uint16_t i = 0; i < SCREEN_DATA_SIZE; i++) {
		screen_data[i] = 0x00;
	}
	return;
}

void fill_out_screen_data_with_ff (void) {
	for (uint16_t i = 0; i < SCREEN_DATA_SIZE; i++) {
		screen_data[i] = 0xFF;
	}
	return;
}

void prepare_screen_data(uint8_t* data, size_t size) {
	for (uint16_t i = 0; i < size; i++) {
		screen_data[i] = data[i];
	}
	return;
}

void out_data_to_the_screen(uint8_t* data, size_t size) {
	prepare_screen_data(data, size);
	fill_out_whole_screen();
	return;
}

